def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", type=Path, default=ROOT / "results")
    parser.add_argument("--output", type=Path, default=ROOT / "paper/docs/EXPERIMENT_MANIFEST.md")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    root = args.results_root.resolve()
    if args.dry_run:
        print("Manifest dry run — no writes or model/binary loading")
        for p in files_under(root):
            print(p)
        return
    output = args.output.resolve()
    if output == root or root in output.parents:
        raise ValueError("manifest output must be outside results inputs")
    output.write_text(render(root), encoding="utf-8")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Build the Stage A reuse map from local metadata; never load model weights.

--dry-run lists every results/ file (including gitignored binary artifacts),
without writing. Only the requested Markdown manifest is written on a full run.
Binary presence is cataloged, not a claim that a checkpoint can be reloaded.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def files_under(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file())


def family(model: str) -> str:
    name = model.lower().replace("qwen--", "")
    return next((f for f in ("gemma3", "qwen3", "olmo3", "gemma4", "muse") if name.startswith(f)), "legacy / unspecified")


def numeric_keys(payload: dict) -> list[str]:
    result = []
    for key in payload:
        try:
            float(key)
        except ValueError:
            continue
        result.append(key)
    return sorted(result, key=float, reverse=True)


def label(path: Path, root: Path) -> str:
    return "results/" + path.relative_to(root).as_posix()


def table(lines: list[str], headers: list[str], rows: list[list]) -> None:
    lines += ["", "| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(v).replace("|", "\\|").replace("\n", " ") for v in row) + " |")
    lines.append("")



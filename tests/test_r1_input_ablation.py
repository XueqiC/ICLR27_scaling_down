"""Recorded-data CPU checks: retrospective (rebuttal round, 2026-11-07)."""
import json

import numpy as np
import pytest

from analysis import r1_input_ablation as r1
from analysis.paper_table_layout import group


@pytest.fixture(scope="module")
def evidence():
    path = r1.ROOT / "results" / r1.ID / "summary.json"
    if not path.exists():
        pytest.skip("Recorded R1 input-ablation results are absent")
    result = json.loads(path.read_text())
    missing = [p for p in result["input_sha256"] if not (r1.ROOT / p).exists()]
    if missing:
        pytest.skip("Recorded input-ablation measurements are absent: " + missing[0])
    return result


@pytest.fixture(scope="module")
def panels(evidence):
    return r1.load_panels()[0]


def test_exact_registered_half_and_full_grids(panels, evidence):
    for panel, counts in (("pythia_magnitude", (18, 36)), ("olmo2_magnitude", (12, 24)), ("pythia_wanda", (18, 36))):
        p = panels[panel]
        for grid, n in zip(("half", "full"), counts):
            assert len(p["grids"][grid]) == n*3
            assert evidence["fits"][panel][grid]["development_rows"] == p["grids"][grid]
        dev = {r["state"] for r in p["grids"]["full"]}
        assert not dev & {r["state"] for r in p["test"]}
        assert len(p["test"]) == (36 if panel == "olmo2_magnitude" else 72)
        for row in p["test"]:
            assert set(row["outcomes"]) == ({"probes"} if panel == "pythia_magnitude" else {"probes", "new"})


def test_delivered_predictions_reproduce_recorded_functions(panels, evidence):
    for name, p in panels.items():
        for grid, dev in p["grids"].items():
            f = evidence["fits"][name][grid]
            for r in p["test"]:
                model = f["models"]["delivered"][r["cap"]]
                pred = float(r1.p53.standardize(r["phi_raw"], f["standardization"]) @ model["beta"] *
                             r1.p53.shape(r["d"], model["gamma"]))
                assert pred == pytest.approx(r["recorded"][grid], abs=1e-9)


@pytest.mark.parametrize("panel,feature", [("pythia_magnitude", "shape"), ("pythia_magnitude", "loss"),
    ("olmo2_magnitude", "loss"), ("olmo2_magnitude", "size_tokens"), ("pythia_wanda", "shape"), ("pythia_wanda", "delivered")])
def test_restricted_features_refit_with_original_estimator(panel, feature, panels, evidence):
    p = panels[panel]
    saved = evidence["fits"][panel]["half"]
    actual = r1.fit_power(p["grids"]["half"], "math", saved["standardization"], feature, p["estimator"])
    old = saved["models"][feature]["math"]
    assert actual["gamma"] == old["gamma"] and actual["ridge"] == old["ridge"]
    np.testing.assert_allclose(actual["beta"], old["beta"], atol=1e-10)
    assert len(actual["beta"]) == len(r1.FEATURES[feature])


def test_all_evaluations_use_same_cells_and_new_item_predictions(evidence):
    assert len(evidence["scores"]) == 120
    for score in evidence["scores"]:
        keys = ("panel", "grid", "feature", "evaluation", "cap")
        rows = [r for r in evidence["cells"] if all(r[k] == score[k] for k in keys)]
        assert len(rows) == score["n_test"]
        assert score["mae"] == pytest.approx(np.mean([abs(r["predicted"]-r["observed"]) for r in rows]), abs=1e-12)
    lookup = {(r["panel"], r["grid"], r["feature"], r["state"], r["cap"], r["d"], r["evaluation"]): r for r in evidence["cells"]}
    for k, row in lookup.items():
        if k[-1] == "new":
            assert row["predicted"] == lookup[(*k[:-1], "probes")]["predicted"]


def test_reproducible_rebuttal_outputs(evidence):
    md, tex = r1.render(evidence)
    assert md == (r1.ROOT / "results" / r1.ID / "summary.md").read_text()
    assert tex == (r1.ROOT / "paper/paper/tables" / (r1.ID+".tex")).read_text()
    assert tex.splitlines()[0] == "% Generated by analysis/r1_input_ablation.py; do not edit."
    assert tex.count(r"\begin{table}") == 1
    assert r"\label{tab:r1-ablation}" in tex
    for part in tex.split(r"\caption")[1:]:
        caption, _ = group(part, 0)
        assert caption.startswith(r"\rev{")
        assert caption.endswith("Retrospective analysis of recorded results (rebuttal round).}")
        _, end = group(caption, 4)
        assert end == len(caption)

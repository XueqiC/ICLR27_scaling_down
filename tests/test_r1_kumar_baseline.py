"""Recorded-data CPU checks: retrospective (rebuttal round, 2026-11-07)."""
import json
from pathlib import Path

import numpy as np
import pytest

from analysis import r1_kumar_baseline as r1
from analysis.paper_table_layout import group


@pytest.fixture(scope="module")
def evidence():
    path = r1.ROOT / "results" / r1.ID / "summary.json"
    if not path.exists():
        pytest.skip("Recorded R1 Kumar results are absent")
    result = json.loads(path.read_text())
    missing = [p for p in result["input_sha256"] if not (r1.ROOT / p).exists()]
    if missing:
        pytest.skip("Recorded Kumar inputs are absent: " + missing[0])
    return result


def test_exact_development_splits_and_original_predictor_replay(evidence):
    panels, _ = r1.load_panels()
    for name, ndev, ntest in (("grouped", 54, 21), ("channel_A", 36, 20), ("channel_B", 24, 20)):
        actual, saved = panels[name], evidence["panels"][name]
        assert len(actual["dev"]) == 3*ndev and len(actual["test"]) == 3*ntest
        assert actual["dev"] == saved["dev"]
        assert actual["development_baseline"] == saved["development_baseline"]
        keys = lambda rows: {(r["state"], r["config"], r["cap"]) for r in rows}
        assert not keys(actual["dev"]) & keys(actual["test"])
        for a, b in zip(actual["test"], saved["test"]):
            assert (a["state"], a["config"], a["cap"], a["y"]) == (b["state"], b["config"], b["cap"], b["y"])
            np.testing.assert_allclose(list(a["comparison_predictions"].values()), list(b["comparison_predictions"].values()), atol=1e-9)
    assert panels["grouped"]["development_baseline"] == {"math": "bilinear", "code": "zero", "qa": "median"}


def test_signed_nonlinear_objective_parameter_counts_and_bootstrap(evidence):
    for name, panel in evidence["panels"].items():
        grouped = panel["adapted"]
        y = np.array([r["y"] for r in panel["dev"]])
        assert np.any(y < 0)
        for variant, fit in panel["fits"].items():
            per_cap = variant == "per_capability"
            expected = (15 if per_cap else 7) if grouped else (12 if per_cap else 6)
            assert fit["n_parameters"] == expected
            assert fit["n_extra_group_parameters"] == ((3 if per_cap else 1) if grouped else 0)
            x, names, _, _ = r1.design(panel["dev"], grouped, per_cap)
            pred = np.exp(x @ fit["parameters"])
            assert np.sum((pred-y)**2) == pytest.approx(fit["sse"], abs=1e-8)
            assert np.all(np.abs(pred[y < 0]-y[y < 0]) >= np.abs(y[y < 0]))
            boot = fit["bootstrap"]
            assert boot["n_resamples"] == 1000 and boot["unit"] == "development state"
            samples = np.asarray(boot["samples"])
            assert samples.shape == (1000, expected) and np.isfinite(samples).all()
            assert not boot["failed_indices"]
            for cap, ex in fit["exponents"].items():
                for exponent in ("gamma_D", "gamma_N"):
                    idx = names.index(f"{cap}:{exponent}" if per_cap else exponent)
                    np.testing.assert_allclose(ex[exponent+"_ci95"], np.quantile(samples[:, idx], [.025, .975]))
                assert ex["gamma_D_positive"] == (ex["gamma_D"] > 0)
                rows = [r for r in panel["dev"] if r["cap"] == cap]
                raw_pred = [np.exp(ex["log_C"]-r["P"]/ex["gamma_post"]+ex["gamma_D"]*np.log(r["D0"])
                                  -ex["gamma_N"]*np.log(r["N0"])+(ex["gamma_g"] or 0)*np.log(r["g"])) for r in rows]
                np.testing.assert_allclose(raw_pred, pred[[r["cap"] == cap for r in panel["dev"]]], rtol=1e-12)


def test_scores_use_identical_cells_and_report_provenance_correction(evidence):
    for panel in evidence["panels"].values():
        cells, scores = r1.evaluate(panel, panel["fits"])
        for actual, saved in zip(scores, panel["scores"]):
            assert actual["n"] == saved["n"] and actual["subset"] == saved["subset"]
            np.testing.assert_allclose(list(actual["mae"].values()), list(saved["mae"].values()), atol=1e-12)
        assert len(cells) == len(panel["test"])
    assert "pruning" in evidence["protocol"]["provenance_correction"]
    assert "V49" in evidence["protocol"]["provenance_correction"]


def test_reproducible_rebuttal_outputs(evidence):
    md, tex = r1.render(evidence)
    assert md == (r1.ROOT / "results" / r1.ID / "summary.md").read_text()
    assert tex == (r1.ROOT / "paper/paper/tables" / (r1.ID+".tex")).read_text()
    assert tex.splitlines()[0] == "% Generated by analysis/r1_kumar_baseline.py; do not edit."
    assert tex.count(r"\begin{table}") == 1
    assert r"\label{tab:r1-kumar}" in tex
    for part in tex.split(r"\caption")[1:]:
        caption, _ = group(part, 0)
        assert caption.startswith(r"\rev{")
        assert caption.endswith("Retrospective analysis of recorded results (rebuttal round).}")
        inner, end = group(caption, 4)
        assert end == len(caption)
    assert "\\resizebox" not in tex

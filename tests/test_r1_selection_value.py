@pytest.fixture(scope="module")
def evidence():
    path = r1.ROOT / "results" / r1.ID / "summary.json"
    if not path.exists():
        pytest.skip("Recorded R1 selection-value results are absent")
    result = json.loads(path.read_text())
    missing = [p for p in result["input_sha256"] if not (r1.ROOT / p).exists()]
    if missing:
        pytest.skip("Recorded selection inputs are absent: " + missing[0])
    return result


def test_replay_sealed_s3_and_heldout_map_choices(evidence):
    # build asserts every original policy ID/regret and both V64 oracle/MAP IDs.
    replay = r1.build()
    assert replay == evidence
    assert len(replay["panels"]["independent"]["rows"]) == 4*4*17
    assert len(replay["panels"]["heldout_pythia_H1"]["rows"]) == 17*4*17
    for target, cohorts in replay["panels"]["heldout_pythia_H1"]["training_cohorts"].items():
        assert all(target not in cohort for cohort in cohorts.values())


def test_cross_method_gaps_errors_and_regrets_from_recorded_candidates(evidence):
    for panel in evidence["panels"].values():
        for row in panel["rows"]:
            candidates = {c["id"]: c for c in row["candidates"]}
            if not candidates:
                assert row["oracle"] is None and row["rank_switch"] is None
                assert row["cross_method_gap"] is None
                continue
            assert all(c["r"] <= row["budget"]+1e-12 for c in candidates.values())
            oracle = candidates[row["oracle"]["id"]]
            assert oracle["actual_loss"] == min(c["actual_loss"] for c in candidates.values())
            other = [c for c in candidates.values() if c["method"] != oracle["method"]]
            if other:
                gap = min(c["actual_loss"] for c in other)-oracle["actual_loss"]
                assert row["cross_method_gap"] == pytest.approx(gap, abs=1e-12)
                assert row["second_method"]["method"] != oracle["method"]
            else:
                assert row["cross_method_gap"] is None
            priority = row["policies"]["priority"]["chosen"]
            assert row["rank_switch"] == (priority["method"] != oracle["method"])
            for name, policy in row["policies"].items():
                if policy["chosen"] is None:
                    assert policy["regret"] is None
                    continue
                chosen = candidates[policy["chosen"]["id"]]
                assert policy["regret"] == pytest.approx(chosen["actual_loss"]-oracle["actual_loss"], abs=1e-12)
                if name in ("median", "rule"):
                    err = lambda c: abs(c["predicted"][name]-c["actual_loss"])
                    assert policy["chosen_abs_error"] == pytest.approx(err(chosen), abs=1e-12)
                    assert policy["oracle_abs_error"] == pytest.approx(err(oracle), abs=1e-12)
                    assert policy["max_feasible_abs_error"] == pytest.approx(max(err(c) for c in candidates.values()), abs=1e-12)
                    if other:
                        assert policy["pair_below_half_gap"] == (max(err(chosen), err(oracle)) < gap/2)
                        assert policy["uniform_method_certificate"] == (2*max(err(c) for c in candidates.values()) < gap)
                    if policy["uniform_method_certificate"]:
                        assert policy["recovered_method"]
                    if policy["uniform_configuration_certificate"]:
                        assert policy["recovered_configuration"]


def test_condition_denominators_and_rank_switch_summaries(evidence):
    for panel in evidence["panels"].values():
        assert r1.aggregate(panel["rows"]) == panel["by_objective"]
        for obj, a in panel["by_objective"].items():
            assert a["n_switch"] <= a["n_feasible"] <= a["n_total"]
            conditions = a["error_conditions"]
            assert conditions["uniform_method_certificate"]["count"] <= conditions["pair_below_half_gap"]["count"]
            assert all(v["denominator"] == a["n_cross_method_gap"] for v in conditions.values())
    assert "not the later S3" in evidence["definitions"]["heldout_rule"]


def test_reproducible_rebuttal_outputs(evidence):
    md, tex = r1.render(evidence)
    assert md == (r1.ROOT / "results" / r1.ID / "summary.md").read_text()
    assert tex == (r1.ROOT / "paper/paper/tables" / (r1.ID+".tex")).read_text()
    assert tex.splitlines()[0] == "% Generated by analysis/r1_selection_value.py; do not edit."
    assert tex.count(r"\begin{table}") == 1
    assert r"\label{tab:r1-selection}" in tex
    for part in tex.split(r"\caption")[1:]:
        caption, _ = group(part, 0)
        assert caption.startswith(r"\rev{")
        assert caption.endswith("Retrospective analysis of recorded results (rebuttal round).}")
        _, end = group(caption, 4)
        assert end == len(caption)
